/**
 * 智能音视频平台 图表高度档位（Stage 6 / BLF-1399）。
 *
 * 背景：改之前，面板里的图表高度由调用方各写各的 —— 248（总览趋势）、
 * 176（设备状态环形图）、168（告警未处置环形图），还有三个组件各自的默认值
 * （230 / 210 / 190 / 150）。同一行里的两个图表卡，一个 248 一个 176，
 * 底边自然对不齐。
 *
 * 口径：图表高度是**内容容器**的量纲，与交互控件高度（`--av-ctl-*`，
 * BLF-1398）不是同一套，也不能与卡片最小高度混用。这里只定三档：
 *
 *   --av-chart-h-lg  248px  主图：趋势 / 柱状（页面的第一视觉重心）
 *   --av-chart-h-md  176px  次图：环形占比、信号曲线（与图例、列表并排）
 *   --av-chart-h-sm  128px  小图：抽屉里的迷你图
 *
 * 同一行内的图表卡用**同一档**；需要主次之分时用 lg + md 配对，
 * 而不是随手写一个中间值。
 *
 * ⚠️ 这三档是**唯一**允许出现在图表 `height` 上的值 ——
 * `web/lib/av/avLayoutTokens.vitest.test.ts` 会扫源码把其它数字挡下来。
 */

/** 图表高度档位（px）。 */
export const AV_CHART_HEIGHT = {
  lg: 248,
  md: 176,
  sm: 128,
} as const;

export type AvChartHeightTier = keyof typeof AV_CHART_HEIGHT;
